const SORTED_KEYS = Object.keys(VI_TERMS).sort((a, b) => b.length - a.length);

/** Translate one exact term; returns the input unchanged when unknown. */
export function viTerm(zh: string | undefined | null): string {
  if (!zh) return "";
  return VI_TERMS[zh] ?? zh;
}

/**
 * Translate a short label made of known terms (e.g. "天机化禄", "甲子", "命宫").
 * Greedy longest-match; adjacent translated terms are joined with a space.
 * Use only for compact labels, never for prose.
 */
export function viTerms(zh: string | undefined | null): string {
  if (!zh) return "";
  if (VI_TERMS[zh]) return VI_TERMS[zh];
  const out: string[] = [];
  let i = 0;
  let raw = "";
  while (i < zh.length) {
    const k = SORTED_KEYS.find((key) => zh.startsWith(key, i));
    if (k) {
      if (raw) { out.push(raw); raw = ""; }
      out.push(VI_TERMS[k]);
      i += k.length;
    } else {
      raw += zh[i++];
    }
  }
  if (raw) out.push(raw);
  return out.join(" ").replace(/\s+/g, " ").trim();
}
