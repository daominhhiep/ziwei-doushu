/**
 * Tên địa danh để hiển thị bằng tiếng Việt. Nhận cả nhãn ghép「地级市·区县」(xem county-label.ts):
 * từng phần được dịch riêng; phần chưa có trong bảng giữ nguyên.
 */
export function placeNameVi(name: string | undefined | null): string {
  if (!name) return '';
  if (PLACE_NAME_VI[name]) return PLACE_NAME_VI[name];
  if (name.includes('·')) return name.split('·').map(part => PLACE_NAME_VI[part] ?? part).join(' · ');
  return name;
}
